type MessageKey = keyof typeof messages.en;

function detectLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === "en" || saved === "zh") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

let currentLocale: Locale = detectLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, locale);
  listeners.forEach((listener) => listener());
}

export function useLocale(): Locale {
  return useSyncExternalStore(
    (listener) => { listeners.add(listener); return () => listeners.delete(listener); },
    () => currentLocale,
    () => "en",
  );
}

export function translate(locale: Locale, key: MessageKey, values?: Record<string, string>): string {
  let message: string = messages[locale][key] ?? messages.en[key];
  for (const [name, value] of Object.entries(values ?? {})) message = message.replace(`{${name}}`, value);
  return message;
}

export function useT(): (key: MessageKey, values?: Record<string, string>) => string {
  const locale = useLocale();
  return useCallback((key, values) => translate(locale, key, values), [locale]);
}

export type { MessageKey };
